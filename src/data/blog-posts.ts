export const getAllPosts = () =>
  [...blogPosts].sort((a, b) => +new Date(b.publishedAt) - +new Date(a.publishedAt));

export const getPostBySlug = (slug: string) => blogPosts.find((p) => p.slug === slug);

export const getPostsByCategory = (categorySlug: string) =>
  getAllPosts().filter((p) => p.categorySlug === categorySlug);

export const getRelatedPosts = (post: BlogPost, limit = 3) => {
  const explicit = post.relatedSlugs
    .map((s) => getPostBySlug(s))
    .filter((p): p is BlogPost => Boolean(p));

  if (explicit.length >= limit) return explicit.slice(0, limit);

  const fallback = getPostsByCategory(post.categorySlug).filter(
    (p) => p.slug !== post.slug && !explicit.some((e) => e.slug === p.slug),
  );

  return [...explicit, ...fallback].slice(0, limit);
};

export const formatDate = (iso: string) =>
  new Date(iso).toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric" });
